def bands_for(test_code: str, scale_code: str) -> tuple[Band, ...]:
    """Return (lo, hi, label, text) tuples for a scale."""
    scales = BANDS.get((test_code or "").strip().lower()) or {}
    found = scales.get(scale_code)
    if not found:
        raise KeyError(f"No interpretation bands for {test_code}.{scale_code}")
    return found


def band_for_score(test_code: str, scale_code: str, score: int) -> tuple[str, str] | None:
    try:
        bands = bands_for(test_code, scale_code)
    except KeyError:
        return None
    for lo, hi, label, text in bands:
        if lo <= score <= hi:
            return label, text
    return None


def iter_scale_bands() -> Iterable[tuple[str, str, tuple[Band, ...]]]:
    for test_code, scales in BANDS.items():
        for scale_code, bands in scales.items():
            yield test_code, scale_code, bands
